export type IconName = keyof typeof map;

export interface IconProps extends Omit<PhosphorProps, 'weight' | 'color'> {
  name: IconName;
  size?: number;
  color?: string;
  weight?: IconWeight;
}

export function Icon({ name, size = 22, color, weight = 'regular', ...rest }: IconProps) {
  const t = useTheme();
  const Cmp = map[name];
  return <Cmp size={size} color={color ?? t.colors.text} weight={weight} {...rest} />;
}
